import fs from 'fs';
import path from 'path';
import { translateFileToMarkdown } from './file-translator.js';

const BINARY_EXTENSIONS = new Set(['.pdf', '.docx', '.xlsx', '.xls', '.bin', '.exe', '.png', '.jpg', '.jpeg']);

/**
 * Audit & Protect Path from Traversal Attacks (../)
 * Ensures paths stay jailed within authorized workspace roots.
 */
export function assertSafePath(targetPath, allowedRoots = []) {
  if (!targetPath || typeof targetPath !== 'string') {
    throw new Error('Path error: target path must be a valid non-empty string.');
  }

  // Normalize path and detect directory traversal attempts
  const normalizedRaw = targetPath.replace(/\\/g, '/');
  const segments = normalizedRaw.split('/');
  if (segments.includes('..') || targetPath.includes('..')) {
    throw new Error(`Path traversal blocked: "${targetPath}" contains unauthorized parent directory references ("..").`);
  }

  const resolved = path.resolve(targetPath);

  // If jail roots are provided, enforce boundaries
  if (allowedRoots && allowedRoots.length > 0) {
    const isContained = allowedRoots.some((root) => {
      const resolvedRoot = path.resolve(root);
      return resolved === resolvedRoot || resolved.startsWith(resolvedRoot + path.sep);
    });
    if (!isContained) {
      throw new Error(`Access denied: "${targetPath}" is outside the authorized workspace directories.`);
    }
  }

  return resolved;
}

/**
 * Safe File Writer (Rule 5: Safe Write Protocol)
 * - Plain-text/Code/Markdown: creates a .bak backup before writing
 * - Read-only binary formats: creates a .ghost.md companion file instead of corrupting binary
 * - Path traversal protection enforced via assertSafePath
 */
export async function safeWriteFile(targetPath, content, allowedRoots = []) {
  const safePath = assertSafePath(targetPath, allowedRoots);
  const ext = path.extname(safePath).toLowerCase();
  const dir = path.dirname(safePath);
  const baseName = path.basename(safePath, ext);

  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  // Read-only binary document format: companion markdown
  if (BINARY_EXTENSIONS.has(ext)) {
    const ghostPath = path.join(dir, `${baseName}${ext}.ghost.md`);
    const header = `<!-- COMPANION FOR: ${path.basename(safePath)} | GENERATED BY: GhostBrain Safe-Write | TIME: ${new Date().toISOString()} -->\n\n`;
    fs.writeFileSync(ghostPath, header + content, 'utf-8');
    return {
      success: true,
      path: ghostPath,
      isCompanion: true,
      originalPath: safePath,
      message: `Binary format protected. Companion Markdown created at ${path.basename(ghostPath)}.`
    };
  }

  // Plain-text, Markdown, Code file
  let backupPath = null;
  if (fs.existsSync(safePath)) {
    backupPath = `${safePath}.bak`;
    fs.copyFileSync(safePath, backupPath);
  }

  fs.writeFileSync(safePath, content, 'utf-8');
  return {
    success: true,
    path: safePath,
    backupPath,
    isCompanion: false,
    message: backupPath
      ? `Updated ${path.basename(safePath)} (backup created at ${path.basename(backupPath)})`
      : `Created ${path.basename(safePath)}`
  };
}

/**
 * Safe File Reader
 * - Text/code/md: reads UTF-8 content directly
 * - Binary documents (.pdf, .docx, .xlsx): returns .ghost.md companion if present, or translates to Markdown
 * - Path traversal protection enforced via assertSafePath
 */
export async function safeReadFile(targetPath, allowedRoots = []) {
  const safePath = assertSafePath(targetPath, allowedRoots);

  if (!fs.existsSync(safePath)) {
    throw new Error(`File not found: ${safePath}`);
  }

  const ext = path.extname(safePath).toLowerCase();
  const dir = path.dirname(safePath);
  const baseName = path.basename(safePath, ext);
  const ghostPath = path.join(dir, `${baseName}${ext}.ghost.md`);

  // If companion exists, return companion markdown
  if (BINARY_EXTENSIONS.has(ext) && fs.existsSync(ghostPath)) {
    return {
      content: fs.readFileSync(ghostPath, 'utf-8'),
      isCompanion: true,
      path: ghostPath,
      type: 'ghost-markdown'
    };
  }

  // If binary document, translate to markdown
  if (BINARY_EXTENSIONS.has(ext)) {
    const translated = await translateFileToMarkdown(safePath);
    return {
      content: translated.markdown,
      isCompanion: false,
      path: safePath,
      type: translated.type
    };
  }

  // Text/code/md file
  return {
    content: fs.readFileSync(safePath, 'utf-8'),
    isCompanion: false,
    path: safePath,
    type: ext.slice(1) || 'text'
  };
}

/**
 * Safe Folder or File Creator
 * Strictly sandboxed within watched directories.
 */
export async function createFolderOrFile(targetPath, isDirectory = false, content = '', allowedRoots = []) {
  const safePath = assertSafePath(targetPath, allowedRoots);

  if (isDirectory) {
    if (!fs.existsSync(safePath)) {
      fs.mkdirSync(safePath, { recursive: true });
    }
    return {
      success: true,
      path: safePath,
      isDirectory: true,
      message: `Created folder at ${safePath}`
    };
  }

  return await safeWriteFile(safePath, content, allowedRoots);
}
