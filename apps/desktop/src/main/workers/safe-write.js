import fs from 'fs';
import path from 'path';
import { translateFileToMarkdown } from './file-translator.js';

const BINARY_EXTENSIONS = new Set(['.pdf', '.docx', '.xlsx', '.xls', '.bin', '.exe', '.png', '.jpg', '.jpeg']);

/**
 * Safe File Writer (Rule 5: Safe Write Protocol)
 * - Plain-text/Code/Markdown: creates a .bak backup before writing
 * - Read-only binary formats: creates a .ghost.md companion file instead of corrupting binary
 */
export async function safeWriteFile(targetPath, content) {
  const ext = path.extname(targetPath).toLowerCase();
  const dir = path.dirname(targetPath);
  const baseName = path.basename(targetPath, ext);

  // Read-only binary document format
  if (BINARY_EXTENSIONS.has(ext)) {
    const ghostPath = path.join(dir, `${baseName}${ext}.ghost.md`);
    const header = `<!-- COMPANION FOR: ${path.basename(targetPath)} | GENERATED BY: GhostBrain Safe-Write | TIME: ${new Date().toISOString()} -->\n\n`;
    fs.writeFileSync(ghostPath, header + content, 'utf-8');
    return {
      success: true,
      path: ghostPath,
      isCompanion: true,
      originalPath: targetPath,
      message: `Binary format protected. Companion Markdown created at ${path.basename(ghostPath)}.`
    };
  }

  // Plain-text, Markdown, Code file
  let backupPath = null;
  if (fs.existsSync(targetPath)) {
    backupPath = `${targetPath}.bak`;
    fs.copyFileSync(targetPath, backupPath);
  }

  fs.writeFileSync(targetPath, content, 'utf-8');
  return {
    success: true,
    path: targetPath,
    backupPath,
    isCompanion: false,
    message: backupPath
      ? `Updated ${path.basename(targetPath)} (backup created at ${path.basename(backupPath)})`
      : `Created ${path.basename(targetPath)}`
  };
}

/**
 * Safe File Reader
 * - Text/code/md: reads UTF-8 content directly
 * - Binary documents (.pdf, .docx, .xlsx): returns .ghost.md companion if present, or translates to Markdown
 */
export async function safeReadFile(targetPath) {
  if (!fs.existsSync(targetPath)) {
    throw new Error(`File not found: ${targetPath}`);
  }

  const ext = path.extname(targetPath).toLowerCase();
  const dir = path.dirname(targetPath);
  const baseName = path.basename(targetPath, ext);
  const ghostPath = path.join(dir, `${baseName}${ext}.ghost.md`);

  // If companion exists, return companion markdown
  if (BINARY_EXTENSIONS.has(ext) && fs.existsSync(ghostPath)) {
    return {
      content: fs.readFileSync(ghostPath, 'utf-8'),
      isCompanion: true,
      path: ghostPath,
      type: 'ghost-markdown'
    };
  }

  // If binary document, translate to markdown
  if (BINARY_EXTENSIONS.has(ext)) {
    const translated = await translateFileToMarkdown(targetPath);
    return {
      content: translated.markdown,
      isCompanion: false,
      path: targetPath,
      type: translated.type
    };
  }

  // Text/code/md file
  return {
    content: fs.readFileSync(targetPath, 'utf-8'),
    isCompanion: false,
    path: targetPath,
    type: ext.slice(1) || 'text'
  };
}
